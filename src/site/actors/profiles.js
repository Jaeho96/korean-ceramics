// 물레 자국: 가로 줄무늬 캔버스를 범프맵으로 쓴다(Lathe 의 v 는 단면을 따라간다)
export function ringsTexture() {
  const c = document.createElement('canvas');
  c.width = 8;
  c.height = 512;
  const g = c.getContext('2d');
  for (let y = 0; y < 512; y++) {
    const v = 128 + 70 * Math.sin(y * 0.55) + 40 * Math.sin(y * 0.13 + 1.3) + (Math.random() - 0.5) * 30;
    g.fillStyle = `rgb(${v},${v},${v})`;
    g.fillRect(0, y, 8, 1);
  }
  return new THREE.CanvasTexture(c);
}
